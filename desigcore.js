  function orgDigits(code) { return code.split('').map(function (c) { var i = ALPHA.indexOf(c) + 1; return i < 10 ? '0' + i : String(i); }).join(''); }
  function orgLetters(d) { var o = ''; for (var i = 0; i < 8; i += 2) { var n = +d.slice(i, i + 2); if (n < 1 || n > 33) return null; o += ALPHA[n - 1]; } return o; }

  /* Проверка одного обозначения. Возвращает { input, norm, parts:[{label, value, note}], issues:[{sev, msg, fix?}], scheme:'imp'|'obj'|'?' , doc } */
  function analyze(raw) {
    var s = String(raw || ''), issues = [], parts = [], res = { input: s, issues: issues, parts: parts };
    function add(sev, msg, fix) { issues.push({ sev: sev, msg: msg, fix: fix || null }); }
    var t = s.replace(/^\s+|\s+$/g, '');
    if (!t) return null;
    if (/^(ГОСТ|ОСТ|ПНСТ|СТО|ТУ|ISO|IEC|DIN|EN)(\s|$)/i.test(t)) {
      res.method = 'std'; res.norm = t;
      add('note', 'Это обозначение стандарта или технических условий, а не изделия по ГОСТ Р 2.201. Проверить, действует ли стандарт, можно на странице «Проверка актуальности ГОСТ».');
      return res;
    }
    // знаки
    var fixed = t;
    if (/\s/.test(t)) { add('err', 'Внутри обозначения есть пробел — по п. 4.6 допускаются только буквы, цифры, точка и дефис.'); fixed = fixed.replace(/\s+/g, ''); }
    var dash = t.match(/[–—−]/);
    if (dash) { add('err', 'Вместо дефиса стоит тире или минус («' + dash[0] + '») — в обозначении применяют дефис.'); fixed = fixed.replace(/[–—−]/g, '-'); }
    if (/[а-яё]/.test(t)) { add('err', 'Строчные буквы не допускаются: по п. 4.6 применяют прописные буквы.'); fixed = fixed.toUpperCase(); }
    var hasCyr = /[А-ЯЁа-яё]/.test(t), lat = t.toUpperCase().match(/[A-Z]/g);
    if (hasCyr && lat) {
      var look = lat.filter(function (c, i, a) { return LAT2CYR[c] && a.indexOf(c) === i; });
      if (look.length) { add('err', 'Латинские буквы среди русских: ' + look.join(', ') + ' — выглядят как русские, но это другие знаки, поиск и сверка по такому обозначению не сработают.'); fixed = fixed.replace(/[ABCEHKMOPTXY]/g, function (c) { return LAT2CYR[c]; }); }
    }
    var bad = t.replace(/[0-9A-Za-zА-ЯЁа-яё.\-‒–—−\s]/g, '');
    if (bad) add('err', 'Недопустимые знаки: «' + bad.split('').filter(function (c, i, a) { return a.indexOf(c) === i; }).join('», «') + '». Допускаются цифры, прописные буквы, точка и дефис.');
    if (fixed !== t) issues.forEach(function (x) { if (x.sev === 'err' && !x.fix) x.fix = fixed; });
    var n = fixed.replace(/‒/g, '-').toUpperCase(), cyr = /[А-ЯЁ]/;
    res.norm = n;

    // 1. обезличенный способ: КОДО.КККККК.ННН[-ИИ[-ДД]][код документа[номер][.часть][.книга]]
    var m = /^([А-ЯЁ]{4}|\d{8})\.(\d{6})\.(\d{3,4})((?:-\d{1,4}){0,2})(?:([.\-]?)([А-ЯЁ]{1,4}\d?)([.\-]?\d{1,3})?([.\-]\d{1,2})?([.\-]\d{1,2})?)?$/.exec(n);
    if (m) {
      res.method = 'imp';
      var org = m[1];
      if (/^\d{8}$/.test(org)) {
        var L = orgLetters(org);
        parts.push({ label: 'Код организации-разработчика', value: org, note: L ? 'цифровая запись буквенного кода ' + L + ' (приложение В)' : 'не соответствует буквенному коду по приложению В' });
        if (!L) add('warn', 'Восьмизначный код организации не раскладывается в буквы по приложению В (пары цифр 01–33).');
      } else parts.push({ label: 'Код организации-разработчика', value: org, note: 'четыре прописные русские буквы (п. 5.2.3); цифровая запись — ' + orgDigits(org) });
      parts.push({ label: 'Код классификационной характеристики', value: m[2], note: 'по ОК 012-93: класс ' + m[2].slice(0, 2) + ', подкласс ' + m[2][2] + ', группа ' + m[2][3] + ', подгруппа ' + m[2][4] + ', вид ' + m[2][5] });
      parts.push({ label: 'Порядковый регистрационный номер', value: m[3], note: m[3].length === 3 ? 'три знака (п. 5.2.5)' : 'увеличен на один знак — допускается по п. 5.2.5' });
      var ex = (m[4] || '').split('-').filter(Boolean);
      if (ex[0]) parts.push({ label: 'Номер исполнения', value: '-' + ex[0], note: 'п. 5.4.5' });
      if (ex[1]) parts.push({ label: 'Дополнительный номер исполнения', value: '-' + ex[1], note: 'п. 5.4.6' });
      if (ex[0] && /^0+$/.test(ex[0])) add('warn', 'Номер исполнения «' + ex[0] + '»: нумерацию исполнений начинают с «01» (п. 5.4.5); базовое исполнение допускается обозначать без номера.');
      if (m[6]) docPart(m[6], [m[7], m[8], m[9]]);
      else parts.push({ label: 'Документ', value: '—', note: ex.length ? 'обозначение исполнения изделия или его основного КД' : 'обозначение изделия или основного КД (без кода вида документа, п. 6.1.2 и ГОСТ Р 2.102, п. 5.5)' });
      return res;
    }
    // 2. похоже на обезличенный, но группы неверные
    if (/^[А-ЯЁ]{2,6}\.\d/.test(n) || /^\d{8}\.\d/.test(n)) {
      res.method = '?';
      var q = n.split('.');
      if (/^[А-ЯЁ]+$/.test(q[0]) && q[0].length !== 4) add('err', 'Код организации-разработчика — ровно четыре прописные русские буквы (п. 5.2.3), а здесь ' + q[0].length + '.');
      var c6 = (q[1] || '').replace(/\D.*$/, '');
      if (c6.length !== 6) add('err', 'Код классификационной характеристики — 6 цифр по ОК 012-93 (п. 5.2.4), а здесь ' + c6.length + '.');
      var r3 = (q[2] || '').replace(/\D.*$/, '');
      if (q.length < 3 || r3.length < 3 || r3.length > 4) add('err', 'Порядковый регистрационный номер — 3 цифры (п. 5.2.5)' + (q.length >= 3 ? ', а здесь ' + r3.length : ', а его нет') + '.');
      if (!issues.some(function (x) { return x.sev === 'err' && !/пробел|тире|Строчные|Латинские|Недопустимые/.test(x.msg); }))
        add('err', 'Не удалось разобрать часть после регистрационного номера. Ожидается вид АБВГ.123456.001[-01][код документа].');
      return res;
    }
    // 3. объектно-ориентированный: группы через точку, код документа — первая буквенная группа после кода изделия
    var g = n.split('.');
    if (g.length >= 2 && /\d/.test(g[0]) && g.every(function (x) { return /^[0-9A-ZА-ЯЁ]+(-[0-9A-ZА-ЯЁ]+)*$/.test(x); })) {
      var di = -1;
      for (var i = 1; i < g.length; i++) if (/^[А-ЯЁ]{1,4}\d?$/.test(g[i])) { di = i; break; }
      var head = di < 0 ? g : g.slice(0, di);
      res.method = 'obj';
      parts.push({ label: 'Код конечного изделия', value: head[0], note: 'объектно-ориентированный способ (п. 5.3.3)' });
      if (head.length > 2) parts.push({ label: 'Позиция в структуре конечного изделия', value: head.slice(1, -1).join('.'), note: 'п. 5.3.4' });
      if (head.length > 1) parts.push({ label: 'Порядковый регистрационный номер', value: head[head.length - 1], note: 'п. 5.3.5' });
      if (di >= 0) {
        var rest = g.slice(di + 1);
        docPart(g[di], [rest[0] ? '.' + rest[0] : '', rest[1] ? '.' + rest[1] : '', rest[2] ? '.' + rest[2] : '']);
        if (rest.length > 3) add('warn', 'После кода документа слишком много групп знаков: ' + rest.slice(3).join('.'));
      } else parts.push({ label: 'Документ', value: '—', note: 'обозначение изделия или основного КД' });
      return res;
    }
    res.method = '?';
    add('warn', 'Структура не распознана как обезличенная (АБВГ.123456.001) или объектно-ориентированная (1101.029000.0000). Возможно, это обозначение по стандарту организации.');
    return res;

    function docPart(code, rest) {
      var dc = docCode(code), num = '';
      var mm = /^([А-ЯЁ]+)(\d)$/.exec(code);
      if (!dc && mm && docCode(mm[1])) { dc = docCode(mm[1]); num = mm[2]; code = mm[1]; }
      if (dc) {
        parts.push({ label: 'Код вида документа', value: code, note: dc.name + ' (' + dc.std + ')' });
        res.doc = dc;
        if (code === 'ЧД' || code === 'СП' || code === 'ЭМД' || code === 'ЭСК') add('note', 'Код «' + code + '» — вид основного КД. По ГОСТ Р 2.102 (п. 5.5) основной КД рекомендуется обозначать без кода вида документа, если в организации не принят другой способ.');
      } else {
        parts.push({ label: 'Код вида документа', value: code, note: 'нет в ГОСТ Р 2.102, ГОСТ Р 2.601, ГОСТ 2.602 и ГОСТ 2.701' });
        add('warn', 'Код вида документа «' + code + '» не найден в ГОСТ Р 2.102, ГОСТ Р 2.601, ГОСТ 2.602 и ГОСТ 2.701 — проверьте или убедитесь, что он установлен стандартом организации.');
      }
      var vals = [num], labels = ['Порядковый номер документа', 'Номер части', 'Номер книги'];
      rest.forEach(function (r) { if (r) vals.push(r.replace(/^[.\-]/, '')); });
      vals = vals.filter(Boolean);
      vals.forEach(function (v, i) { if (i < 3) parts.push({ label: labels[i], value: v, note: i === 0 ? 'п. 6.1.6' + (res.doc && res.doc.kind !== 'graf' ? '; у текстового документа это может быть и номер части (п. 6.3)' : '') : 'п. 6.3' }); });
    }
  }

  /* Сборка обозначения */
  function build(o) {
    o = o || {};
    var org = String(o.org || '').toUpperCase().trim(), cls = String(o.cls || '').trim(), reg = String(o.reg || '').trim();
    var s = org + '.' + cls + '.' + reg;
    if (o.isp) s += '-' + String(o.isp).trim();
    if (o.isp2) s += '-' + String(o.isp2).trim();
    if (o.code) s += (o.sep || '') + o.code + (o.num ? String(o.num) : '') + (o.part ? (o.num ? '.' : '') + o.part : '') + (o.book ? '.' + o.book : '');
    return s;
  }
  function docName(product, code) {
    var dc = code ? docCode(code) : null;
    if (!dc) return product || '';
    return (product ? product + '. ' : '') + dc.name;
  }

  var api = { DOCS: DOCS, docCode: docCode, schemeCode: schemeCode, SCH_KIND: SCH_KIND, SCH_TYPE: SCH_TYPE, analyze: analyze, build: build, docName: docName, orgDigits: orgDigits, orgLetters: orgLetters, VERSION: '0.1' };
  if (typeof module !== 'undefined' && module.exports) module.exports = api; else root.DESIG = api;
