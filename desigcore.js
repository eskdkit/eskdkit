  function schemeCode(s) {
    var m = /^([ПТ]?)([ЭГПХКВЛРЕС])([0-7])$/.exec(s);
    if (!m) return null;
    var name = 'Схема ' + SCH_KIND[m[2]] + ' ' + SCH_TYPE[m[3]];
    if (m[1] === 'П') name = 'Перечень элементов (к схеме ' + SCH_KIND[m[2]].replace(/ая$/, 'ой') + ' ' + SCH_TYPE[m[3]].replace(/ая$/, 'ой') + ')';
    if (m[1] === 'Т') name = 'Таблица (к схеме ' + SCH_KIND[m[2]].replace(/ая$/, 'ой') + ' ' + SCH_TYPE[m[3]].replace(/ая$/, 'ой') + ')';
    if (m[1] === 'П' && m[2] === 'П' && false) return null;
    return { code: s, name: name, std: 'ГОСТ 2.701', kind: 'sch' };
  }
